-- 1. CERTIFICADOS DE VALORIZACIÓN
SELECT *
FROM T_CERTIFICADO_VALORIZACION
ORDER BY NRO_CERTIFICADO;

-- 2. DECLARACIONES POM
SELECT *
FROM T_DECLARACION_POM
ORDER BY FK_ID_PRODUCTOR, FK_ID_MATERIALIDAD, ANIO;

-- 3. LOTES DE RECOLECCIÓN
SELECT *
FROM T_LOTE_RECOLECCION
ORDER BY NRO_LOTE;

-- 4. MATERIALIDADES
SELECT *
FROM T_MATERIALIDAD
ORDER BY ID_MATERIALIDAD;

-- 5. PLANTAS RECICLADORAS
SELECT P.ID_PLANTA, P.RUT_PLANTA, P.NOMBRE_PLANTA,
       C.NOMBRE_COMUNA AS COMUNA, P.RESOLUCION_SANITARIA
FROM T_PLANTA_RECICLADORA P, T_COMUNA C
WHERE P.FK_ID_COMUNA = C.ID_COMUNA
ORDER BY P.ID_PLANTA;

-- 6. PRODUCTORES
SELECT *
FROM T_PRODUCTOR
ORDER BY ID_PRODUCTOR;

-- 7. PUNTOS DE ACOPIO
SELECT P.ID_PUNTO, P.NOMBRE_PUNTO, P.TIPO_PUNTO,
       P.DIRECCION, C.NOMBRE_COMUNA AS COMUNA, P.CAPACIDAD_M3
FROM T_PUNTO_ACOPIO P, T_COMUNA C
WHERE P.FK_ID_COMUNA = C.ID_COMUNA
ORDER BY P.ID_PUNTO;

-- 8. SUBPRODUCTOS
SELECT *
FROM T_SUBPRODUCTO
ORDER BY ID_SUBPRODUCTO;

-- 9. TRANSFORMACIONES DE LOTES
SELECT *
FROM T_TRANSFORMACION_LOTE
ORDER BY FK_NRO_LOTE, FK_ID_SUBPRODUCTO;

-- 10. TRANSPORTISTAS
SELECT *
FROM T_TRANSPORTISTA
ORDER BY ID_TRANSPORTISTA;


-- Consulta 1
SELECT NRO_LOTE,
       PESO_BRUTO_KG,
       PESO_BRUTO_KG * PORC_CONTAMINACION / 100                         AS KG_CONTAMINACION,
       PESO_BRUTO_KG - (PESO_BRUTO_KG * PORC_CONTAMINACION / 100)       AS PESO_NETO
FROM   T_LOTE_RECOLECCION
WHERE  ESTADO_LOTE = 'Clasificado'
ORDER BY PESO_NETO DESC;

-- Consulta 2
SELECT P.NOMBRE_PUNTO || ' - ' || C.NOMBRE_COMUNA AS PUNTO,
       P.TIPO_PUNTO,
       P.CAPACIDAD_M3
FROM   T_PUNTO_ACOPIO P
       JOIN T_COMUNA C ON C.ID_COMUNA = P.FK_ID_COMUNA
WHERE  P.TIPO_PUNTO IN ('Punto Limpio', 'Centro de Acopio')
AND    P.CAPACIDAD_M3 BETWEEN 30 AND 400
ORDER BY P.CAPACIDAD_M3 ASC;