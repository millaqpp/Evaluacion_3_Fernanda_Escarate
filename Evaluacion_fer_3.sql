-- TABLA: T_MATERIALIDAD
CREATE TABLE T_MATERIALIDAD (
    ID_MATERIALIDAD            NUMBER NOT NULL,
    NOMBRE_MATERIALIDAD        VARCHAR2(40) NOT NULL,
    META_VALORIZACION_PCT      NUMBER(5,2) NOT NULL,
    CONSTRAINT PK_MATERIALIDAD PRIMARY KEY (ID_MATERIALIDAD)
);

-- TABLA: T_PRODUCTOR
CREATE TABLE T_PRODUCTOR (
    ID_PRODUCTOR               NUMBER NOT NULL,
    RUT_PRODUCTOR              VARCHAR2(12) NOT NULL,
    RAZON_SOCIAL               VARCHAR2(100) NOT NULL,
    EMAIL_CONTACTO             VARCHAR2(100),
    CONSTRAINT PK_PRODUCTOR PRIMARY KEY (ID_PRODUCTOR)
);

-- TABLA: T_COMUNA
CREATE TABLE T_COMUNA (
    ID_COMUNA                  NUMBER NOT NULL,
    NOMBRE_COMUNA              VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_COMUNA PRIMARY KEY (ID_COMUNA),
    CONSTRAINT UN_COMUNA_NOMBRE_COMUNA UNIQUE (NOMBRE_COMUNA)
);

-- TABLA: T_PLANTA_RECICLADORA
CREATE TABLE T_PLANTA_RECICLADORA (
    ID_PLANTA                  NUMBER NOT NULL,
    RUT_PLANTA                 VARCHAR2(12) NOT NULL,
    NOMBRE_PLANTA              VARCHAR2(80) NOT NULL,
    FK_ID_COMUNA               NUMBER NOT NULL,
    RESOLUCION_SANITARIA       VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_PLANTA_RECICLADORA PRIMARY KEY (ID_PLANTA)
);

-- TABLA: T_DECLARACION_POM
CREATE TABLE T_DECLARACION_POM (
    FK_ID_PRODUCTOR            NUMBER NOT NULL,
    FK_ID_MATERIALIDAD         NUMBER NOT NULL,
    ANIO                       NUMBER(4) NOT NULL,
    TONELADAS_DECLARADAS       NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_DECLARACION_POM PRIMARY KEY (FK_ID_PRODUCTOR, FK_ID_MATERIALIDAD, ANIO)
);

-- TABLA: T_TRANSPORTISTA
CREATE TABLE T_TRANSPORTISTA (
    ID_TRANSPORTISTA           NUMBER NOT NULL,
    RUT_TRANSPORTISTA          VARCHAR2(12) NOT NULL,
    NOMBRE_TRANSPORTISTA       VARCHAR2(100) NOT NULL,
    PATENTE_CAMION             VARCHAR2(8) NOT NULL,
    CONSTRAINT PK_TRANSPORTISTA PRIMARY KEY (ID_TRANSPORTISTA),
    CONSTRAINT UN_TRANSPORTIST_RUT_TRANSPORTI UNIQUE (RUT_TRANSPORTISTA)
);

-- TABLA: T_PUNTO_ACOPIO
CREATE TABLE T_PUNTO_ACOPIO (
    ID_PUNTO                   NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 1) NOT NULL,
    NOMBRE_PUNTO               VARCHAR2(80) NOT NULL,
    TIPO_PUNTO                 VARCHAR2(20) NOT NULL,
    DIRECCION                  VARCHAR2(120) NOT NULL,
    FK_ID_COMUNA               NUMBER NOT NULL,
    CAPACIDAD_M3               NUMBER(6,1) NOT NULL,
    CONSTRAINT PK_PUNTO_ACOPIO PRIMARY KEY (ID_PUNTO)
);

-- TABLA: T_LOTE_RECOLECCION
CREATE TABLE T_LOTE_RECOLECCION (
    NRO_LOTE                   NUMBER NOT NULL,
    FK_ID_PUNTO                NUMBER NOT NULL,
    FK_ID_MATERIALIDAD         NUMBER NOT NULL,
    FK_ID_TRANSPORTISTA        NUMBER NOT NULL,
    FECHA_RECOLECCION          DATE NOT NULL,
    PESO_BRUTO_KG              NUMBER(10,2) NOT NULL,
    PORC_CONTAMINACION         NUMBER(5,2) NOT NULL,
    ESTADO_LOTE                VARCHAR2(15) NOT NULL,
    CONSTRAINT PK_LOTE_RECOLECCION PRIMARY KEY (NRO_LOTE)
);

-- TABLA: T_SUBPRODUCTO
CREATE TABLE T_SUBPRODUCTO (
    ID_SUBPRODUCTO             NUMBER NOT NULL,
    NOMBRE_SUBPRODUCTO         VARCHAR2(60) NOT NULL,
    FK_ID_MATERIALIDAD         NUMBER NOT NULL,
    PRECIO_TONELADA            NUMBER(10) NOT NULL,
    CONSTRAINT PK_SUBPRODUCTO PRIMARY KEY (ID_SUBPRODUCTO)
);

-- TABLA: T_TRANSFORMACION_LOTE
CREATE TABLE T_TRANSFORMACION_LOTE (
    FK_NRO_LOTE                NUMBER NOT NULL,
    FK_ID_SUBPRODUCTO          NUMBER NOT NULL,
    KG_OBTENIDOS               NUMBER(10,2) NOT NULL,
    CONSTRAINT PK_TRANSFORMACION_LOTE PRIMARY KEY (FK_NRO_LOTE, FK_ID_SUBPRODUCTO)
);

-- TABLA: T_CERTIFICADO_VALORIZACION
CREATE TABLE T_CERTIFICADO_VALORIZACION (
    NRO_CERTIFICADO            VARCHAR2(15) NOT NULL,
    FK_NRO_LOTE                NUMBER NOT NULL,
    FK_ID_PLANTA               NUMBER NOT NULL,
    FK_ID_PRODUCTOR            NUMBER NOT NULL,
    FECHA_EMISION              DATE NOT NULL,
    KG_VALORIZADOS             NUMBER(10,2) NOT NULL,
    KG_MERMA                   NUMBER(10,2) NOT NULL,
    TRATAMIENTO                VARCHAR2(25) NOT NULL,
    CONSTRAINT PK_CERTIFICADO_VALORIZACION PRIMARY KEY (NRO_CERTIFICADO)
);

